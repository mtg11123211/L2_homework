#ifndef IO_CAMERA_HPP
#define IO_CAMERA_HPP

// ============================================================================
// camera.hpp —— 作业一：把海康 MVS SDK 的 C 风格取流流程封装成 Camera 类
// ----------------------------------------------------------------------------
// 作业的两条硬性要求（必须能向学长指出对应位置）：
//   1) 公有成员只有三个函数：构造函数 Camera()、析构函数 ~Camera()、read()
//   2) 私有成员变量命名必须以 '_' 结尾 —— 本类只有一个：handle_
//
// 设计思想（学长可能追问）：
//   * RAII：资源获取即初始化。构造函数里完成"枚举->打开->配参->开始取流"，
//           析构函数按相反顺序释放，对象离开作用域时相机一定被正确关闭，
//           即使中间抛异常或程序 return，也不会出现"相机被占用、下次打不开"。
//   * 信息隐藏：海康 SDK 的头文件 MvCameraControl.h 只在 camera.cpp 里包含，
//           头文件里用 void* 存句柄。上层（main.cpp）完全感知不到海康 SDK，
//           以后换别的品牌相机，只要改 .cpp，上层代码一行不动。
// ============================================================================

#include <opencv2/opencv.hpp>  // 只用了 cv::Mat 作为 read() 的返回类型

class Camera
{
public:
  // 构造函数：拿到对象时相机就已经可用（已打开、参数已配好、已在取流）。
  // 任何一步失败都会抛出 std::runtime_error，对象不会被"构造一半"。
  Camera();

  // 析构函数：停止取流 -> 关闭设备 -> 销毁句柄，与构造顺序严格相反。
  // 不可以省略：句柄是 SDK 内部资源，不释放会导致相机一直被占用。
  ~Camera();

  // 读取一帧图像，返回三通道 BGR 的 cv::Mat（与 cv::imshow 的通道序一致）。
  // 取帧超时/失败时返回空 Mat，调用方用 img.empty() 判断后跳过本帧即可，
  // 不采用抛异常的方式——实时视频里偶尔丢一帧是正常现象，不该让程序退出。
  cv::Mat read();

private:
  // 海康 SDK 的相机句柄。SDK 里真实类型是 void*（MV_CC_CreateHandle 的出参），
  // 这里直接以 void* 保存，头文件就不需要 #include "MvCameraControl.h"。
  // 命名以 '_' 结尾，满足作业命名要求，同时与普通局部变量区分开。
  void * handle_;
};

#endif  // IO_CAMERA_HPP
